export type IconName = keyof typeof PATHS

export const icon = (name: IconName, size = 18) =>
  `<svg class="icon" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" ` +
  `stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${PATHS[name]}</svg>`

/** Fill every `<i data-icon="name">` placeholder in the document. */
export function renderIcons(root: ParentNode = document) {
  root.querySelectorAll<HTMLElement>('i[data-icon]').forEach((el) => {
    el.outerHTML = icon(el.dataset.icon as IconName, Number(el.dataset.size) || undefined)
  })
}
